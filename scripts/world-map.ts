// Writes src/lib/ui/world-map-shapes.ts, WorldMap's country outlines, projected once here so apps ship
// plain SVG paths instead of a projection library: `node scripts/world-map.ts`. Re-run after a world-atlas update.
import { writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { geoNaturalEarth1, geoPath } from 'd3-geo';
import { feature } from 'topojson-client';
import countries from 'i18n-iso-countries';
import type { Feature, FeatureCollection, MultiPolygon, Polygon } from 'geojson';
import type { Topology } from 'topojson-specification';

const require = createRequire(import.meta.url);
const WIDTH = 960;

type Shape = Feature<Polygon | MultiPolygon, { name: string }>;
const load = (file: string) => {
	const topo = require(`world-atlas/${file}`) as Topology;
	return (feature(topo, topo.objects.countries) as FeatureCollection<Polygon | MultiPolygon>)
		.features as Shape[];
};
// Natural Earth leaves out a code where ISO has none; Kosovo has a user-assigned one everyone uses.
const codeOf = (f: Shape) =>
	f.properties.name === 'Kosovo'
		? 'XK'
		: f.id
			? countries.numericToAlpha2(String(f.id))
			: undefined;

const land = load('countries-110m.json').filter((f) => codeOf(f) !== 'AQ');
const projection = geoNaturalEarth1().fitWidth(WIDTH, {
	type: 'FeatureCollection',
	features: land
});
const path = geoPath(projection).digits(1);
const height = Math.ceil(path.bounds({ type: 'FeatureCollection', features: land })[1][1]);

// A label point inside the biggest piece, so France sits in Europe rather than between it and Guiana.
function centroid(f: Shape): [number, number] {
	const parts: Polygon[] =
		f.geometry.type === 'Polygon'
			? [f.geometry]
			: f.geometry.coordinates.map((coordinates) => ({ type: 'Polygon', coordinates }));
	const biggest = parts.reduce((a, b) => (path.area(b) > path.area(a) ? b : a));
	return path.centroid(biggest).map((n) => Math.round(n * 10) / 10) as [number, number];
}

const shapes = land.map((f) => [codeOf(f) ?? '', path(f) ?? '', ...centroid(f)] as const);
const drawn = new Set(shapes.map(([code]) => code));
// Countries too small for the 110m outlines (Singapore, Bahrain, Malta…) get a dot at their 50m centroid.
const dots = load('countries-50m.json')
	.map((f) => [codeOf(f), ...centroid(f)] as const)
	.filter(([code]) => code && code !== 'AQ' && !drawn.has(code))
	.sort(([a], [b]) => a!.localeCompare(b!));

await writeFile(
	'src/lib/ui/world-map-shapes.ts',
	`// Generated by scripts/world-map.ts from Natural Earth (public domain) via world-atlas; don't edit.
// Natural Earth projection, ${WIDTH}×${height}, Antarctica left out. [ISO alpha-2 ('' for none), path, centroid x, y]
export const size = [${WIDTH}, ${height}] as const;
export const shapes: [string, string, number, number][] = ${JSON.stringify(shapes)};
/** Countries too small to draw at this scale, as [code, x, y]. */
export const dots: [string, number, number][] = ${JSON.stringify(dots)};
`
);
console.log(`${shapes.length} shapes, ${dots.length} dots, ${WIDTH}×${height}`);
